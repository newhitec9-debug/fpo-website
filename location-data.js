/*
========================================================
PIN MASTER

अभी PIN केवल उन्हीं villages में भरेंगे
जिनका PIN अलग से verify हो चुका हो।
गलत PIN automatic नहीं लगाया जाएगा।
========================================================
*/

const PIN_MASTER = {};


/*
========================================================
GET STATES
========================================================
*/

function getLocationStates(){

    return Object.keys(
        LOCATION_MASTER
    );

}


/*
========================================================
GET DISTRICTS
========================================================
*/

function getLocationDistricts(
    state
){

    if(
        !LOCATION_MASTER[state]
    ){

        return [];

    }

    return Object.keys(
        LOCATION_MASTER[state]
    ).sort();

}


/*
========================================================
GET TEHSILS
========================================================
*/

function getLocationTehsils(
    state,
    district
){

    if(
        !LOCATION_MASTER[state] ||
        !LOCATION_MASTER[state][district]
    ){

        return [];

    }

    return Object.keys(
        LOCATION_MASTER[state][district]
    ).sort();

}


/*
========================================================
GET BLOCKS
========================================================
*/

function getLocationBlocks(
    state,
    district,
    tehsil
){

    if(
        !LOCATION_MASTER[state] ||
        !LOCATION_MASTER[state][district] ||
        !LOCATION_MASTER[state][district][tehsil]
    ){

        return [];

    }

    return Object.keys(
        LOCATION_MASTER[state]
        [district]
        [tehsil]
    ).sort();

}


/*
========================================================
GET VILLAGES
========================================================
*/

function getLocationVillages(
    state,
    district,
    tehsil,
    block
){

    if(
        !LOCATION_MASTER[state] ||
        !LOCATION_MASTER[state][district] ||
        !LOCATION_MASTER[state][district][tehsil] ||
        !LOCATION_MASTER[state][district][tehsil][block]
    ){

        return [];

    }

    return LOCATION_MASTER[state]
        [district]
        [tehsil]
        [block]
        .map(
            function(village){

                return {

                    name: village,

                    pincode:
                    getVillagePin(
                        state,
                        district,
                        tehsil,
                        block,
                        village
                    )

                };

            }
        )
        .sort(
            function(a,b){

                return a.name.localeCompare(
                    b.name,
                    "hi"
                );

            }
        );

}


/*
========================================================
GET PIN
========================================================
*/

function getVillagePin(
    state,
    district,
    tehsil,
    block,
    village
){

    if(
        PIN_MASTER[state] &&
        PIN_MASTER[state][district] &&
        PIN_MASTER[state][district][tehsil] &&
        PIN_MASTER[state][district][tehsil][block] &&
        PIN_MASTER[state][district][tehsil][block][village]
    ){

        return PIN_MASTER[state]
            [district]
            [tehsil]
            [block]
            [village];

    }

    return "";

}


/*
========================================================
FIND VILLAGE
========================================================
*/

function findLocationVillage(
    state,
    district,
    tehsil,
    block,
    village
){

    const villages =
    getLocationVillages(
        state,
        district,
        tehsil,
        block
    );

    return villages.find(
        function(item){

            return item.name === village;

        }
    ) || null;

}


/*
========================================================
AUTOMATIC ADDRESS
========================================================
*/

function buildFarmerAddress(
    village,
    block,
    tehsil,
    district,
    state,
    pincode = ""
){

    const parts = [];

    if(village)
        parts.push(village);

    if(block)
        parts.push(block);

    if(tehsil)
        parts.push(tehsil);

    if(district)
        parts.push(district);

    if(state)
        parts.push(state);

    if(pincode)
        parts.push(pincode);

    return parts.join(", ");

}


/*
========================================================
ADD VILLAGE
========================================================
*/

function addLocationVillage(
    state,
    district,
    tehsil,
    block,
    village,
    pincode = ""
){

    if(
        !LOCATION_MASTER[state]
    ){

        LOCATION_MASTER[state] = {};

    }

    if(
        !LOCATION_MASTER[state][district]
    ){

        LOCATION_MASTER[state][district] = {};

    }

    if(
        !LOCATION_MASTER[state][district][tehsil]
    ){

        LOCATION_MASTER[state][district][tehsil] = {};

    }

    if(
        !LOCATION_MASTER[state]
        [district]
        [tehsil]
        [block]
    ){

        LOCATION_MASTER[state]
        [district]
        [tehsil]
        [block] = [];

    }

    const villages =
    LOCATION_MASTER[state]
    [district]
    [tehsil]
    [block];

    if(
        !villages.includes(village)
    ){

        villages.push(village);

    }

    if(pincode){

        if(
            !PIN_MASTER[state]
        )
            PIN_MASTER[state] = {};

        if(
            !PIN_MASTER[state][district]
        )
            PIN_MASTER[state][district] = {};

        if(
            !PIN_MASTER[state]
            [district]
            [tehsil]
        )
            PIN_MASTER[state]
            [district]
            [tehsil] = {};

        if(
            !PIN_MASTER[state]
            [district]
            [tehsil]
            [block]
        )
            PIN_MASTER[state]
            [district]
            [tehsil]
            [block] = {};

        PIN_MASTER[state]
        [district]
        [tehsil]
        [block]
        [village] = pincode;

    }

}


