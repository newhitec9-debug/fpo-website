/*
========================================================
PIN MASTER
========================================================
*/

const PIN_MASTER = {};


/*
========================================================
STATES
========================================================
*/

function getLocationStates(){

    return Object.keys(
        LOCATION_MASTER
    );

}


/*
========================================================
DISTRICTS
========================================================
*/

function getLocationDistricts(
    state
){

    return Object.keys(
        LOCATION_MASTER[state] || {}
    ).sort();

}


/*
========================================================
TEHSILS
========================================================
*/

function getLocationTehsils(
    state,
    district
){

    return Object.keys(
        LOCATION_MASTER[state]?.[district] || {}
    ).sort();

}


/*
========================================================
BLOCKS
========================================================
*/

function getLocationBlocks(
    state,
    district,
    tehsil
){

    return Object.keys(
        LOCATION_MASTER[state]?.[district]?.[tehsil] || {}
    ).sort();

}


/*
========================================================
VILLAGES
========================================================
*/

function getLocationVillages(
    state,
    district,
    tehsil,
    block
){

    const villages =
        LOCATION_MASTER
        [state]
        ?.[district]
        ?.[tehsil]
        ?.[block];


    if(!Array.isArray(villages)){

        return [];

    }


    return villages
        .map(
            function(village){

                return {

                    name: village,

                    pincode:
                        getVillagePin(
                            state,
                            district,
                            tehsil,
                            block,
                            village
                        )

                };

            }
        )
        .sort(
            function(a,b){

                return a.name.localeCompare(
                    b.name,
                    "hi"
                );

            }
        );

}


/*
========================================================
PIN
========================================================
*/

function getVillagePin(
    state,
    district,
    tehsil,
    block,
    village
){

    return (
        PIN_MASTER
        [state]
        ?.[district]
        ?.[tehsil]
        ?.[block]
        ?.[village]
        || ""
    );

}


/*
========================================================
FIND VILLAGE
========================================================
*/

function findLocationVillage(
    state,
    district,
    tehsil,
    block,
    village
){

    return getLocationVillages(
        state,
        district,
        tehsil,
        block
    ).find(
        function(item){

            return item.name === village;

        }
    ) || null;

}


/*
========================================================
AUTOMATIC ADDRESS
========================================================
*/

function buildFarmerAddress(
    village,
    block,
    tehsil,
    district,
    state,
    pincode = ""
){

    const parts = [];

    if(village)
        parts.push(village);

    if(block)
        parts.push(block);

    if(tehsil)
        parts.push(tehsil);

    if(district)
        parts.push(district);

    if(state)
        parts.push(state);

    if(pincode)
        parts.push(pincode);

    return parts.join(", ");

}


/*
========================================================
ADD VILLAGE
========================================================
*/

function addLocationVillage(
    state,
    district,
    tehsil,
    block,
    village,
    pincode = ""
){

    if(!LOCATION_MASTER[state])
        LOCATION_MASTER[state] = {};

    if(!LOCATION_MASTER[state][district])
        LOCATION_MASTER[state][district] = {};

    if(!LOCATION_MASTER[state][district][tehsil])
        LOCATION_MASTER[state][district][tehsil] = {};

    if(!LOCATION_MASTER[state][district][tehsil][block])
        LOCATION_MASTER[state][district][tehsil][block] = [];

    const list =
        LOCATION_MASTER[state]
        [district]
        [tehsil]
        [block];


    if(!list.includes(village)){

        list.push(village);

    }


    if(pincode){

        if(!PIN_MASTER[state])
            PIN_MASTER[state] = {};

        if(!PIN_MASTER[state][district])
            PIN_MASTER[state][district] = {};

        if(!PIN_MASTER[state][district][tehsil])
            PIN_MASTER[state][district][tehsil] = {};

        if(!PIN_MASTER[state][district][tehsil][block])
            PIN_MASTER[state][district][tehsil][block] = {};

        PIN_MASTER[state]
        [district]
        [tehsil]
        [block]
        [village] = pincode;

    }

}


