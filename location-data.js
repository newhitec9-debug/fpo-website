/*
============================================================
HELPER FUNCTIONS
============================================================
*/


function locationNormalize(value){

    return String(value || "")
        .trim()
        .replace(/\s+/g, " ");

}


/*
============================================================
GET STATES
============================================================
*/

function getLocationStates(){

    return Object.keys(
        LOCATION_MASTER
    );

}


/*
============================================================
GET DISTRICTS
============================================================
*/

function getLocationDistricts(
    state
){

    if(
        !LOCATION_MASTER[state]
    ){

        return [];

    }

    return Object.keys(
        LOCATION_MASTER[state]
    ).sort();

}


/*
============================================================
GET TEHSILS
============================================================
*/

function getLocationTehsils(
    state,
    district
){

    if(
        !LOCATION_MASTER[state] ||
        !LOCATION_MASTER[state][district]
    ){

        return [];

    }

    return Object.keys(
        LOCATION_MASTER[state][district]
    ).sort();

}


/*
============================================================
GET BLOCKS
============================================================
*/

function getLocationBlocks(
    state,
    district,
    tehsil
){

    if(
        !LOCATION_MASTER[state] ||
        !LOCATION_MASTER[state][district] ||
        !LOCATION_MASTER[state][district][tehsil]
    ){

        return [];

    }

    return Object.keys(
        LOCATION_MASTER[state][district][tehsil]
    ).sort();

}


/*
============================================================
GET VILLAGES
============================================================
*/

function getLocationVillages(
    state,
    district,
    tehsil,
    block
){

    if(
        !LOCATION_MASTER[state] ||
        !LOCATION_MASTER[state][district] ||
        !LOCATION_MASTER[state][district][tehsil] ||
        !LOCATION_MASTER[state][district][tehsil][block]
    ){

        return [];

    }

    return LOCATION_MASTER
        [state]
        [district]
        [tehsil]
        [block]
        .slice()
        .sort(
            (a,b) =>
            a.name.localeCompare(
                b.name,
                "hi"
            )
        );

}


/*
============================================================
FIND VILLAGE
============================================================
*/

function findLocationVillage(
    state,
    district,
    tehsil,
    block,
    village
){

    const villages =
    getLocationVillages(
        state,
        district,
        tehsil,
        block
    );

    return villages.find(
        item =>
        item.name === village
    ) || null;

}


/*
============================================================
AUTOMATIC ADDRESS
============================================================
*/

function buildFarmerAddress(
    village,
    block,
    tehsil,
    district,
    state,
    pincode = ""
){

    const parts = [];

    if(village)
        parts.push(village);

    if(block)
        parts.push(block);

    if(tehsil)
        parts.push(tehsil);

    if(district)
        parts.push(district);

    if(state)
        parts.push(state);

    if(pincode)
        parts.push(pincode);

    return parts.join(", ");

}


/*
============================================================
ADD VILLAGE
============================================================
*/

function addLocationVillage(
    state,
    district,
    tehsil,
    block,
    village,
    pincode = ""
){

    village =
    locationNormalize(village);

    if(!village)
        return;

    if(!LOCATION_MASTER[state])
        LOCATION_MASTER[state] = {};

    if(!LOCATION_MASTER[state][district])
        LOCATION_MASTER[state][district] = {};

    if(!LOCATION_MASTER[state][district][tehsil])
        LOCATION_MASTER[state][district][tehsil] = {};

    if(!LOCATION_MASTER[state][district][tehsil][block])
        LOCATION_MASTER[state][district][tehsil][block] = [];

    const list =
    LOCATION_MASTER
        [state]
        [district]
        [tehsil]
        [block];

    const exists =
    list.some(
        item =>
        item.name === village
    );

    if(!exists){

        list.push({

            name:village,

            pincode:pincode

        });

    }

}


